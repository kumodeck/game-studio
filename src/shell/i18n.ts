const TABLES: Record<Lang, Partial<Record<Key, string>>> = { en, ja };

/**
 * The person's AI by name in every string (studio-words-plan, 2026-10-23; glossary rule 4 "the AI by its own name, never
 * mixed on one screen"): the field said "Ask Claude to change the game…" while a picked object's chip said "Ask your AI…"
 * and the timeline "Ask AI". Now a string writes {ai} / {Ai} (an English sentence's start) / {ai2} (its second mention, ja
 * shorter) and translate() fills them from the AI the editor last heard from — main.ts calls setAiName() when the
 * status says who it is. Until then (or with no AI): "your AI" (ai.name.any). Vars a caller passes still win.
 */
let aiKey: 'claude' | 'codex' | 'any' = 'any';
export function setAiName(k: 'claude' | 'codex' | 'any'): void {
  aiKey = k;
}
function aiDefaults(lang: Lang): Record<string, string> {
  const look = (key: string) => (TABLES[lang] as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? '';
  const ai = look(`ai.name.${aiKey}`);
  return { ai, Ai: ai.charAt(0).toUpperCase() + ai.slice(1), ai2: look(`ai.name2.${aiKey}`) };
}
/** Strings added or replaced by .studio/ui/shell.js (studioShell.setText). */
const EXTRA: Record<Lang, Record<string, string>> = { en: {}, ja: {} };

export function setExtraText(lang: Lang, strings: Record<string, string>): void {
  for (const [k, v] of Object.entries(strings || {})) if (typeof v === 'string') EXTRA[lang][k] = v;
}

export function detectLang(search: string, navLang: string): Lang {
  const q = new URLSearchParams(search).get('lang');
  if (q === 'en' || q === 'ja') return q;
  return navLang.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function translate(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const s = EXTRA[lang][key] ?? (TABLES[lang] as Record<string, string>)[key] ?? EXTRA.en[key] ?? (en as Record<string, string>)[key] ?? key;
  if (/\{(ai|Ai|ai2)\}/.test(s)) vars = { ...aiDefaults(lang), ...vars };
  return plural(s, vars).replace(/\{(\w+)\}/g, (_m, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/**
 * "{n:1 unsaved change|# unsaved changes}" → the first part when n is 1, else the second with # = n.
 * WHY (words pass 2026-10-17): "1 change(s)" read as machine output to North American players
 * (play test 2026-10-16). Japanese has no plural, so the ja table just uses {n}. Also used by
 * the Assets strings (tools/library/strings.ts).
 */
export function plural(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+):([^{}|]*)\|([^{}]*)\}/g, (m, k: string, one: string, other: string) =>
    k in vars ? (Number(vars[k]) === 1 ? one : other).replace(/#/g, String(vars[k])) : m);
}
